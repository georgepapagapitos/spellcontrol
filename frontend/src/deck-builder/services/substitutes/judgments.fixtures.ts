/**
 * Pooled substitute judgments (E517): "for ROLE, how well does C stand in for
 * Q?", graded 0-3 on the scale of cardFacts/substitutes.fixtures.ts, for the
 * queries of that file. They exist so the substitute rankers can be scored on
 * the candidates they actually surface, not only on the few pairs lane B
 * wrote down (TREC-style pooling).
 *
 * HOW THEY WERE MADE
 *  1. Pool: for each of lane B's (card, role) queries, the top 5 of every
 *     ranker under test over the whole commander-legal universe (the shipped
 *     owned-lane and Similar-strip rankers, and v2), minus pairs already
 *     graded. `node scripts/substitute-eval.mjs --pool <file>` writes the
 *     pool with each card's Scryfall oracle text.
 *  2. Grade: two annotators graded every pair independently from the oracle
 *     text alone, against a written rubric (the scale above plus per-role
 *     notes: scope, speed, cost, and the polarity rule, where the same words
 *     aimed at the wrong player grade 0). Nothing here comes from the tagger
 *     corpus, the card-facts extractor or EDHREC: a ranker built on those
 *     signals is never graded against labels derived from them.
 *  3. Agree: Krippendorff's alpha (ordinal) over the two annotators is
 *     reported per round below. Every disagreement was adjudicated by reading
 *     both oracle texts; `ab` keeps the two original grades on those rows.
 *     A seeded sample of agreements was re-read as a spot check.
 *
 * Round 1 (the shipped rankers and the unfitted v2 prior): 929 pairs over
 * 80 queries, alpha 0.896 (exact agreement 77%, 3 pairs apart by 2+), 210
 * adjudicated, 45 agreements spot-checked, none changed.
 * Round 2 (the fitted v2, v2 minus structure, v2 minus EDHREC, and the
 * shipped owned lane without EDHREC): 430 pairs over 79 queries, alpha 0.871
 * (exact 81%, none apart by 2+), 82 adjudicated, 25 agreements spot-checked,
 * none changed.
 * Round 3 (the sign-constrained v2): 58 pairs over 35 queries, alpha 0.829
 * (exact 83%), 10 adjudicated, 6 agreements spot-checked, none changed.
 *
 * Directional: a row grades C as a replacement for Q. Lane B's rows are
 * symmetric; these are not (a strictly better card can be a 3 one way and a
 * 2 the other).
 */
export interface Judgment {
  q: string;
  c: string;
  role: string;
  grade: 0 | 1 | 2 | 3;
  /** The two annotators' grades, on rows where they disagreed and `grade` was adjudicated. */
  ab?: [number, number];
}

