#!/usr/bin/env node
// Builds src/flavor-names.ts — every printing whose card face carries a name
// other than its oracle name. Scryfall calls it `flavor_name`: the Final
// Fantasy "through the ages" printing of Light Up the Stage reads "A Promise
// Fulfilled", the Godzilla series renames whole monsters, Secret Lair does it
// most drops. ~660 printings, so it ships as a table in this package rather
// than a runtime fetch: the frontend and the backend's shared-binder
// projection both sort and search by it synchronously, and no stored card
// (collection row, frozen deck copy, share) has to carry or backfill it.
//
// Keyed `set:collector_number` (set lowercased), because every card shape in
// the app carries those two and not always a Scryfall id. Double-faced
// printings keep their flavor names on the faces; those join with " // ", the
// same way the oracle name joins its faces.
//
// Run by hand (`node scripts/refresh-flavor-names.mjs`) or by the scheduled
// refresh-snapshots workflow. Fails loudly: nothing runs it at build time.

import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const dest = resolve(here, '..', 'src', 'flavor-names.ts');

let url = 'https://api.scryfall.com/cards/search?q=has%3Aflavorname&unique=prints&order=set';
const entries = [];
while (url) {
  const res = await fetch(url, {
    headers: { 'User-Agent': 'SpellControl/1.0', Accept: 'application/json' },
  });
  if (!res.ok) throw new Error(`[flavor-names] HTTP ${res.status} for ${url}`);
  const page = await res.json();
  for (const card of page.data) {
    const faces = card.card_faces ?? [];
    const flavor =
      card.flavor_name ??
      (faces.some((f) => f.flavor_name)
        ? faces.map((f, i) => f.flavor_name ?? card.name.split(' // ')[i]).join(' // ')
        : undefined);
    if (flavor && flavor !== card.name) {
      entries.push([`${card.set.toLowerCase()}:${card.collector_number}`, flavor]);
    }
  }
  url = page.has_more ? page.next_page : null;
  // Scryfall asks for 50–100ms between requests.
  if (url) await new Promise((r) => setTimeout(r, 120));
}

// A sudden collapse means the query or the API changed, not that Secret Lair
// stopped printing flavor names. Refuse to overwrite a good table with it.
if (entries.length < 500) {
  throw new Error(`[flavor-names] only ${entries.length} printings came back; keeping the table`);
}

entries.sort(([a], [b]) => a.localeCompare(b));
const body = `// Generated by scripts/refresh-flavor-names.mjs from Scryfall. Do not edit by hand.

/** Flavor name by \`set:collector_number\` (set lowercased). */
export const FLAVOR_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(entries))};
`;
const options = { ...(await resolveConfig(dest)), filepath: dest };
await writeFile(dest, await format(body, options));
console.log(`[flavor-names] wrote ${entries.length} printings to ${dest}`);
